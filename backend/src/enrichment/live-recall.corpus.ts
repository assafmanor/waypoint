// The recall corpus the live probe runs (ADR-0166 §22). Read `live-recall.probe.spec.ts` first.
//
// **`name` is the name the app would have SAVED, not the name the place has.** Google is asked
// with `languageCode=he` (ADR-0108), so the normal case is a HEBREW name — which is why most of
// this corpus is Hebrew and why the same place appears twice, once in each script: that pairing
// is the controlled comparison, same pin and same expected QID with only the alphabet changed.
// A minor local feature arrives in its own Latin spelling instead, routinely with an English
// feature-type word appended (`Brúarfoss Waterfall`), which is its own failure class.
//
// `lat`/`lng` are the visitor pin. `expect` is the QID a correct match reaches, or `refuse`
// where any match at all would be a false positive — the controls are not decoration, they are
// half the measurement, and a change that raises the score while matching one of them is a
// regression.
//
// **Provenance.** Every `expect` QID was read from the live API (`en.wikipedia.org` page →
// `wikibase_item`) on 2026-08-11, not recalled. The pins are visitor coordinates rather than
// captured Google responses — the app's own Google pin for these places has never been seen in
// a session, so a case whose verdict turns on a hundred metres is evidence about the radius,
// not about the place. Three of them do; they are noted in the session note, not hidden here.

